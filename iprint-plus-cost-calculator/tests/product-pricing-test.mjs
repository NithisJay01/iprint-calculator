import assert from 'node:assert/strict';
import { newProduct, validateSettings, calculateProductPrice } from '../shared/product-pricing.js';
import { calculateBusinessCardQuote, buildOrderPayload } from '../business-card/logic.js';
const p = newProduct();
const input = { product:p, quantity:500, sheets:20, baseCost:74, services:[{id:'print',price:30,unit:'sheet'},{id:'coat',price:20,unit:'sheet'}], date:'2026-09-17' };
assert.equal(calculateProductPrice(input).total,1396.2);
p.mode='packages';p.packages=[{id:'corporate',name:'Corporate',quantity:500,price:900}];p.includedServiceIds=['print'];input.packageId='corporate';
assert.equal(calculateProductPrice(input).total,1420);
assert.throws(()=>calculateProductPrice({...input,quantity:499}));
p.promotions=[{id:'sale',name:'Sale',enabled:true,type:'percent',scope:'base',value:10,minQuantity:500,minSpend:900,code:'SAVE',start:'2026-09-17',end:'2026-09-17'}];
assert.equal(calculateProductPrice(input).discount,0);
input.code='save';assert.equal(calculateProductPrice(input).total,1330);
assert.equal(calculateProductPrice({...input,date:'2026-09-18'}).discount,0);
p.promotions.push({...p.promotions[0],id:'better',type:'fixed',value:100});
assert.equal(calculateProductPrice(input).discount,100);
p.minimum=1400;p.rounding=100;assert.equal(calculateProductPrice(input).total,1400);
p.minimum=0;p.rounding=.01;p.promotions=[];p.mode='tiers';p.tiers=[{min:100,price:5},{min:500,price:3}];
assert.equal(calculateProductPrice(input).base,1500);
assert.equal(calculateProductPrice({...input,quantity:499}).base,2495);
assert.throws(()=>calculateProductPrice({...input,quantity:99}));
p.materialIds=['allowed'];assert.throws(()=>calculateProductPrice(input));p.materialIds=[];
p.enabled=false;assert.throws(()=>calculateProductPrice(input));p.enabled=true;
p.tiers.push({min:100,price:2});assert.equal(validateSettings({products:[p]}).success,false);p.tiers.pop();
assert.equal(validateSettings({products:[p,p]}).success,false);
p.rounding=0;assert.equal(validateSettings({products:[p]}).success,false);p.rounding=.01;p.mode='formula';
const preset={id:'paper',usableW:31.02,usableH:47.26};const material={id:'m',price:1.2,unit:'sheet'};
const quote=calculateBusinessCardQuote({preset,material,services:input.services,quantity:500,pricingSettings:{version:'v1',products:[p]},boost:{multiplier:.2}});
assert.equal(quote.price,1675.44);
const order=buildOrderPayload({state:{preset,material,services:input.services,boost:{days:1,multiplier:.2}},quote,orderKey:'test',quoteNo:'TEST'});
assert.equal(order.orderItems[0].pricingSnapshot.version,'v1');
p.markup=99;assert.equal(order.orderItems[0].pricingSnapshot.rule.markup,30);
console.log('Product pricing tests passed');

// The Worker recomputes configured prices and replaces client snapshots.
const { verifyConfiguredPrice } = await import('../worker/domain/product-pricing.js');
const pricingSettings={version:'v1',products:[{...newProduct()}]};
const configuredItem={...order.orderItems[0],productId:'business-card'};
assert.equal(verifyConfiguredPrice(configuredItem,pricingSettings).total,1396.2);
assert.throws(()=>verifyConfiguredPrice({...configuredItem,basePrice:1},pricingSettings));
assert.throws(()=>verifyConfiguredPrice(configuredItem,{...pricingSettings,version:'v2'}));
assert.throws(()=>verifyConfiguredPrice({...configuredItem,pricingSnapshot:null},pricingSettings));
for(const bad of [null, {products:[null]}, {products:[{...newProduct(),name:123}]}, {products:[{...newProduct(),tiers:[null]}]}]) assert.equal(validateSettings(bad).success,false);
